-- Audit H12 (area 7): pictures to remove from the image provider (Cloudinary) after someone deletes their account.
-- The API cannot delete them itself (the upload preset is public and the server holds no Cloudinary secret), so it
-- writes their ADDRESSES here, with no link to the person, and the owner empties the queue with scripts/purge-cloudinary.sh.
create table image_erasure_queue (
    queue_id bigint generated by default as identity primary key,
    image_url varchar(500) not null unique,
    queued_at timestamp not null default now()
);
