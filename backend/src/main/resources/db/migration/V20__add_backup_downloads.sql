-- Admin "Download backup": a log of the last 50 downloads, so the admin page can show them and the limits survive a restart.
-- Deliberately holds NO email, name or IP address: only when, which admin (a number, no foreign key so the row outlives an admin
-- account), how many bytes, whether the download completed, and whether the alert email to the admin could be sent.
create table backup_downloads (
    id bigint generated by default as identity primary key,
    downloaded_at timestamp not null default now(),
    admin_user_id bigint not null,
    bytes bigint not null,
    ok boolean not null,
    alert_sent boolean not null
);
create index idx_backup_downloads_admin_time on backup_downloads (admin_user_id, downloaded_at);
