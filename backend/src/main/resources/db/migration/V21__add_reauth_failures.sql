-- Audit backup review (M1): wrong passwords typed to prove "it is me" (delete account, password change, email change, backup download)
-- are counted HERE, not in memory, so a restart cannot reset the count. One row per wrong attempt: only the account number and the time
-- (no password, no IP, no email). Rows older than a day are removed as new ones are written; an account's rows go with the account.
create table reauth_failures (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    failed_at timestamp not null default now()
);
create index idx_reauth_failures_user_time on reauth_failures (user_id, failed_at);
