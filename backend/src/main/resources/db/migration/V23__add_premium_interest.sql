-- "Request Premium": while payments (Stripe) are not switched on, a signed-in adult can say they would want Premium, so demand can be measured.
-- One row per account (unique user id) and nothing else: no free text, no email, no name. There is deliberately no foreign key: the row is
-- deleted with the account by the account erasure itself (and is part of "download my data").
create table premium_interest (
    id bigint generated by default as identity primary key,
    user_id bigint not null unique,
    created_at timestamp not null default now()
);
